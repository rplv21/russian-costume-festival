export type FreeDay = { value: string; label: string; date: string };

export const FREE_DAYS: FreeDay[] = [
  { value: '16', label: '16 октября — Первый день', date: '16 октября 2026' },
  { value: '17', label: '17 октября — Второй день', date: '17 октября 2026' },
];

export function isValidDay(value: unknown): value is string {
  return typeof value === 'string' && FREE_DAYS.some((d) => d.value === value);
}

export function seatLabel(seatId: string): string {
  const found = SEAT_INDEX.get(seatId);
  if (!found) return seatId;
  const { section, seat } = found;
  if (seat.row === 0) return `${section.label}, Место ${seat.num}`;
  return `${section.label}, Ряд ${seat.row}, Место ${seat.num}`;
}
